function normal(shader, t_base, t_second, t_detail)
    shader:begin("stub_notransform_t", "ui_texture_blend")
        :fog(false)
        :zb(false, false)
        :blend(true, blend.srcalpha, blend.invsrcalpha)
    shader:dx10texture("s_base", t_base)
    shader:dx10texture("s_blend_alt", t_second)
    shader:dx10texture("s_blend_mask", t_detail)
    shader:dx10sampler("smp_base")
end
