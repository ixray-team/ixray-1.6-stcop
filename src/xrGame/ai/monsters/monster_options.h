template <typename S>
inline bool Has(const CInifile* Settings, const S& Section, const char* Key)
{
	const SLocation Value = Resolve(Settings, SectionName(Section), Key);
	return Settings && Value.Section && Value.Key && *Value.Key && Settings->line_exist(Value.Section, Value.Key);
}

template <typename T, typename S>
inline T Read(const CInifile* Settings, const S& Section, const char* Key, T Default)
{
	if (!Settings) { return Default; }
	const SLocation Value = Resolve(Settings, SectionName(Section), Key);
	return Settings->read_if_exists<T>(Value.Section, Value.Key, Default);
}

template <typename S>
inline const char* String(const CInifile* Settings, const S& Section, const char* Key)
{
	const SLocation Value = Resolve(Settings, SectionName(Section), Key);
	return Settings->r_string(Value.Section, Value.Key);
}

