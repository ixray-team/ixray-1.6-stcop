struct SLocation
{
	const char* Section;
	const char* Key;
};

inline const char* SectionName(const char* Name) { return Name; }
inline const char* SectionName(const shared_str& Name) { return Name.c_str(); }

inline SLocation Resolve(const CInifile* Settings, const char* Section, const char* Key)
{
	if (!Settings || !Section || !*Section || !Key || !*Key)
	{
		return {Section, Key};
	}
	auto Found = std::lower_bound(std::begin(Keys), std::end(Keys), Key, [](const SKey& Item, const char* Name)
	{
		return xr_stricmp(Item.Legacy, Name) < 0;
	});
	if (Found == std::end(Keys) || xr_stricmp(Found->Legacy, Key) != 0)
	{
		// New callers may use the canonical eel__ property directly as well.
		Found = std::find_if(std::begin(Keys), std::end(Keys), [Key](const SKey& Item)
		{
			return xr_stricmp(Item.Key, Key) == 0;
		});
		if (Found == std::end(Keys)) { return {Section, Key}; }
	}
	if (Settings->line_exist(Section, Found->Key))
	{
		return {Section, Found->Key};
	}
	if (Settings->line_exist(Section, Found->Link))
	{
		const char* Options = Settings->r_string(Section, Found->Link);
		if (Options && *Options && Settings->section_exist(Options) && Settings->line_exist(Options, Found->Key))
		{
			return {Options, Found->Key};
		}
	}
	return {Section, Key};
}

