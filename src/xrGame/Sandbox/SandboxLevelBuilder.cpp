// A missing link is encoded as the all-ones 26-bit value; every consumer
// (pathing, the AI grid editor) treats link >= vertex_count as "no link".
constexpr u32 NoLink = LevelGraph::NodeUncompressed::LINK_MASK_0;

// Link direction convention (mirrors the editor/compiler): -X, +Z, +X, -Z.
constexpr int LinkDX[4] = { -1, 0, 1, 0 };
constexpr int LinkDZ[4] = { 0, 1, 0, -1 };

static bool WriteLevelLtx(const char* levelDir)
{
	const xr_string Path = xr_string(levelDir) + "\\level.ltx";
	IWriter* Writer = FS.w_open(Path.c_str());
	if (Writer == nullptr || !Writer->valid())
	{
		Msg("! Sandbox::BuildLevel: cannot open '%s' for writing", Path.c_str());
		if (Writer)
			FS.w_close(Writer);
		return false;
	}
	Writer->w_printf("; Sandbox level generated by Sandbox::BuildLevel\r\n");
	// An empty [level_scripts] section is legal: the loader starts an empty
	// script process when no 'script' line is present.
	Writer->w_printf("\r\n[level_scripts]\r\n");
	FS.w_close(Writer);
	return true;
}

static bool WriteLevelCform(const STerrainParams& terrain, const char* levelDir)
{
	const xr_string CformBase = xr_string(levelDir) + "\\level";

	if (terrain.Kind == ETerrainKind::PrebuiltLevel)
	{
		// Byte-exact copy keeps parity with the stock collision loader; the
		// source may live loose or inside a game archive.
		const xr_string SourceName = terrain.PrebuiltLevel + "\\level.cform";
		IReader* Source = FS.r_open(_game_levels_, SourceName.c_str());
		if (Source == nullptr)
		{
			Msg("! Sandbox::BuildLevel: prebuilt level '%s' has no level.cform, falling back to flat terrain", terrain.PrebuiltLevel.c_str());
			STerrainParams Fallback = terrain;
			Fallback.Kind = ETerrainKind::Flat;
			STerrainMesh FallbackMesh = BuildTerrainMesh(Fallback);
			XRay::CForm::CFormatVanilla FallbackFormat;
			FallbackFormat.AddStaticGeom(FallbackMesh.Verts, FallbackMesh.Tris);
			// XRay::CForm::Write appends ".cform" to the file name itself.
			XRay::CForm::Write(CformBase.c_str(), FallbackFormat);
			return std::filesystem::exists((CformBase + ".cform").c_str());
		}

		const xr_string Target = CformBase + ".cform";
		IWriter* Writer = FS.w_open(Target.c_str());
		if (Writer == nullptr || !Writer->valid())
		{
			Msg("! Sandbox::BuildLevel: cannot open '%s' for writing", Target.c_str());
			if (Writer)
				FS.w_close(Writer);
			FS.r_close(Source);
			return false;
		}
		Writer->w(Source->pointer(), u32(Source->length()));
		FS.w_close(Writer);
		FS.r_close(Source);
		return true;
	}

	STerrainMesh Mesh = BuildTerrainMesh(terrain);
	if (Mesh.Verts.empty() || Mesh.Tris.empty())
	{
		Msg("! Sandbox::BuildLevel: terrain mesh is empty");
		return false;
	}

	XRay::CForm::CFormatVanilla Format;
	Format.AddStaticGeom(Mesh.Verts, Mesh.Tris);
	// XRay::CForm::Write appends ".cform" to the file name itself.
	XRay::CForm::Write(CformBase.c_str(), Format);
	if (!std::filesystem::exists((CformBase + ".cform").c_str()))
	{
		Msg("! Sandbox::BuildLevel: failed to write '%s.cform'", CformBase.c_str());
		return false;
	}
	return true;
}

bool WriteLevelAi(const STerrainParams& terrain, const char* outputPath)
{
	if (terrain.Cell <= 0.f || terrain.Size <= 0.f)
	{
		Msg("! Sandbox::WriteLevelAi: invalid terrain size/cell");
		return false;
	}

	STerrainParams Sampling = terrain;
	if (Sampling.Kind == ETerrainKind::PrebuiltLevel)
	{
		// HACK: no procedural surface exists for a prebuilt level; a flat grid
		// at y = 0 keeps the AI map structurally valid.
		Msg("! Sandbox::WriteLevelAi: prebuilt level '%s' has no procedural surface, writing a flat AI grid", Sampling.PrebuiltLevel.c_str());
		Sampling.Kind = ETerrainKind::Flat;
	}

	const int Cells = std::max(1, iFloor(Sampling.Size / Sampling.Cell + 0.5f));
	const int NodesX = Cells + 1;
	const int NodesZ = Cells + 1;
	const u32 NodeCount = u32(NodesX * NodesZ);
	if (NodeCount >= NoLink)
	{
		Msg("! Sandbox::WriteLevelAi: node count %u exceeds the link capacity", NodeCount);
		return false;
	}

	// BuildTerrainMesh shares the grid derivation below (same cell count, same
	// origin), and it caches heightmap reads — reuse its vertices directly.
	STerrainMesh Mesh = BuildTerrainMesh(Sampling);
	if (Mesh.Verts.size() != NodeCount)
	{
		Msg("! Sandbox::WriteLevelAi: internal grid mismatch");
		return false;
	}

	hdrNODES Header = {};
	Header.version = XRAI_LARGE_VERSION;
	Header.count = NodeCount;
	Header.size = Sampling.Cell;
	Header.aabb = Mesh.Bounds;
	Header.size_y = Mesh.Bounds.max.y - Mesh.Bounds.min.y + EPS_L;
	Header.guid = generate_guid();

	// Mirrors the reader side: row_length == NodesZ for this regular grid.
	const u32 RowLength = u32(iFloor((Header.aabb.max.z - Header.aabb.min.z) / Header.size + EPS_L + 1.5f));

	IWriter* Writer = FS.w_open(outputPath);
	if (Writer == nullptr || !Writer->valid())
	{
		Msg("! Sandbox::WriteLevelAi: cannot open '%s' for writing", outputPath);
		if (Writer)
			FS.w_close(Writer);
		return false;
	}

	Writer->w(&Header, sizeof(Header));

	const auto HeightAt = [&Mesh, NodesX, NodesZ](int X, int Z) -> float
	{
		X = clampr(X, 0, NodesX - 1);
		Z = clampr(Z, 0, NodesZ - 1);
		return Mesh.Verts[size_t(Z) * size_t(NodesX) + size_t(X)].y;
	};

	// Nodes are emitted sorted by packed xz (x-major), so the node id equals
	// CellX * RowLength + CellZ.
	for (int X = 0; X < NodesX; ++X)
	{
		for (int Z = 0; Z < NodesZ; ++Z)
		{
			const Fvector& Position = Mesh.Verts[size_t(Z) * size_t(NodesX) + size_t(X)];

			// Position packing mirrors ILevelGraph::vertex_position(CPosition&, const Fvector&).
			const int CellX = iFloor((Position.x - Header.aabb.min.x) / Header.size + .5f);
			const int CellZ = iFloor((Position.z - Header.aabb.min.z) / Header.size + .5f);
			const u32 Pxz = u32(CellX) * RowLength + u32(CellZ);
			int Py = iFloor(65535.f * (Position.y - Header.aabb.min.y) / Header.size_y + EPS_S);
			clamp(Py, 0, 65535);

			// Plane normal from central differences of the node heights.
			const float Hx = HeightAt(X + 1, Z) - HeightAt(X - 1, Z);
			const float Hz = HeightAt(X, Z + 1) - HeightAt(X, Z - 1);
			Fvector Normal;
			Normal.set(-Hx / (2.f * Sampling.Cell), 1.f, -Hz / (2.f * Sampling.Cell));
			Normal.normalize_safe();

			LevelGraph::CVertex Vertex = {};
			Vertex.UncompressedNode.p.xz(Pxz);
			Vertex.UncompressedNode.p.y(u16(Py));
			Vertex.UncompressedNode.plane = pvCompress(Normal);
			// Open terrain: full standing height, no low cover.
			Vertex.UncompressedNode.high.cover0 = 15;
			Vertex.UncompressedNode.high.cover1 = 15;
			Vertex.UncompressedNode.high.cover2 = 15;
			Vertex.UncompressedNode.high.cover3 = 15;

			// 4-neighbor grid links; border nodes get the no-link sentinel.
			u32 Links[4] = { NoLink, NoLink, NoLink, NoLink };
			for (u8 Direction = 0; Direction < 4; ++Direction)
			{
				const int Nx = X + LinkDX[Direction];
				const int Nz = Z + LinkDZ[Direction];
				if (Nx < 0 || Nz < 0 || Nx >= NodesX || Nz >= NodesZ)
					continue;
				Links[Direction] = u32(Nx) * RowLength + u32(Nz);
			}

			LevelGraphFormat::WriteNode(*Writer, XRAI_LARGE_VERSION, Vertex, Links, 0);
		}
	}

	FS.w_close(Writer);
	return true;
}

void WriteLevelGame(IWriter& writer, const STerrainParams& terrain)
{
	// One square patrol loop over the terrain so AI has a usable path.
	const float Offset = terrain.Size * 0.3f;
	Fvector Points[4];
	Points[0].set(-Offset, 0.f, -Offset);
	Points[1].set(Offset, 0.f, -Offset);
	Points[2].set(Offset, 0.f, Offset);
	Points[3].set(-Offset, 0.f, Offset);
	for (u32 I = 0; I < 4; ++I)
		Points[I].y = SampleHeight(terrain, Points[I].x, Points[I].z);

	writer.open_chunk(WAY_PATROLPATH_CHUNK);
	{
		// Sub-chunk #0: one path.
		writer.open_chunk(0);
		{
			writer.open_chunk(WAYOBJECT_CHUNK_VERSION);
			writer.w_u16(WAYOBJECT_VERSION);
			writer.close_chunk();

			writer.open_chunk(WAYOBJECT_CHUNK_NAME);
			writer.w_stringZ("viewer_patrol");
			writer.close_chunk();

			writer.open_chunk(WAYOBJECT_CHUNK_POINTS);
			writer.w_u16(4);
			for (u32 I = 0; I < 4; ++I)
			{
				writer.w_fvector3(Points[I]);
				writer.w_u32(0); // flags
				string16 PointName;
				xr_sprintf(PointName, "wp_%u", I);
				writer.w_stringZ(PointName);
			}
			writer.close_chunk();

			writer.open_chunk(WAYOBJECT_CHUNK_LINKS);
			writer.w_u16(4);
			for (u16 I = 0; I < 4; ++I)
			{
				writer.w_u16(I);
				writer.w_u16(u16((u32(I) + 1) % 4));
				writer.w_float(1.f);
			}
			writer.close_chunk();
		}
		writer.close_chunk();
	}
	writer.close_chunk();
}

static bool WriteLevelGameFile(const STerrainParams& terrain, const char* levelDir)
{
	const xr_string Path = xr_string(levelDir) + "\\level.game";
	IWriter* Writer = FS.w_open(Path.c_str());
	if (Writer == nullptr || !Writer->valid())
	{
		Msg("! Sandbox::BuildLevel: cannot open '%s' for writing", Path.c_str());
		if (Writer)
			FS.w_close(Writer);
		return false;
	}
	WriteLevelGame(*Writer, terrain);
	FS.w_close(Writer);
	return true;
}

static bool WriteLevelSom(const char* levelDir)
{
	const xr_string path = xr_string(levelDir) + "\\level.som";
	IWriter* stream = FS.w_open(path.c_str());
	if (stream == nullptr || !stream->valid())
	{
		Msg("! Sandbox::BuildLevel: cannot open '%s' for writing", path.c_str());
		if (stream != nullptr)
			FS.w_close(stream);
		return false;
	}

	CMemoryWriter data;
	data.open_chunk(0);
	data.w_u32(0);
	data.close_chunk();
	data.open_chunk(1);
	struct SSomPolygon
	{
		Fvector3 V1;
		Fvector3 V2;
		Fvector3 V3;
		u32 TwoSided;
		float Occlusion;
	};
	const SSomPolygon polygons[] =
	{
		{ { 0.f, 0.f, 0.f }, { 0.f, 0.f, 1.f }, { 1.f, 0.f, 0.f }, 1, 0.75f },
		{ { 1.f, 0.f, 0.f }, { 0.f, 0.f, 1.f }, { 1.f, 0.f, 1.f }, 1, 0.75f },
	};
	data.w(polygons, sizeof(polygons));
	data.close_chunk();
	stream->w(data.pointer(), data.size());
	FS.w_close(stream);
	return true;
}

bool BuildLevel(const STerrainParams& terrain, const char* folderName, const Flags32& resourceMask)
{
	if (folderName == nullptr || folderName[0] == 0)
	{
		Msg("! Sandbox::BuildLevel: empty folder name");
		return false;
	}

	string_path LevelDir;
	FS.update_path(LevelDir, _game_levels_, folderName);
	Msg("* Sandbox::BuildLevel: building '%s' -> '%s'", folderName, LevelDir);

	std::error_code Ec;
	std::filesystem::create_directories(LevelDir, Ec);
	if (Ec)
	{
		Msg("! Sandbox::BuildLevel: cannot create '%s': %s", LevelDir, Ec.message().c_str());
		return false;
	}

	// level.ltx is always written; a config-less level is legal (the loader
	// falls back to an empty config) but a minimal one keeps the log clean.
	if (!WriteLevelLtx(LevelDir))
		return false;

	Msg("* Sandbox::BuildLevel: '%s' collision", folderName);
	if (resourceMask.test(u32(ELevelResource::Collision)) && !WriteLevelCform(terrain, LevelDir))
		return false;

	Msg("* Sandbox::BuildLevel: '%s' AI-map", folderName);
	if (resourceMask.test(u32(ELevelResource::AiMap)))
	{
		const xr_string AiPath = xr_string(LevelDir) + "\\level.ai";
		if (!WriteLevelAi(terrain, AiPath.c_str()))
			return false;
	}

	Msg("* Sandbox::BuildLevel: '%s' patrol and sound", folderName);
	if (resourceMask.test(u32(ELevelResource::PatrolPaths)) && !WriteLevelGameFile(terrain, LevelDir))
		return false;

	if (resourceMask.test(u32(ELevelResource::SoundEnv)) && !WriteLevelSom(LevelDir))
		return false;
	Msg("* Sandbox::BuildLevel: '%s' VFS registration", folderName);

	// The FS caches directory listings at boot; newly created folders and files
	// are invisible to it until registered. Register the folder entry and every
	// written file explicitly.
	FS.RegisterFolder(LevelDir);
	{
		std::error_code dirEc;
		for (const std::filesystem::directory_entry& entry : std::filesystem::directory_iterator(LevelDir, dirEc))
			FS.file_update(entry.path().string().c_str());
	}

	return true;
}

void RemoveLevel(const char* folderName)
{
	if (folderName == nullptr || folderName[0] == 0)
		return;

	string_path LevelDir;
	FS.update_path(LevelDir, _game_levels_, folderName);

	// Drop every file from the VFS index AND disk (file_delete does both), so a
	// later rebuild with a different resource mask leaves no stale VFS entries
	// (FS.exist would otherwise report a deleted file and r_open would fatal).
	{
		std::error_code listEc;
		for (const std::filesystem::directory_entry& entry : std::filesystem::directory_iterator(LevelDir, listEc))
			FS.file_delete(entry.path().string().c_str());
	}

	std::error_code Ec;
	std::filesystem::remove_all(LevelDir, Ec);
	if (Ec)
		Msg("! Sandbox::RemoveLevel: failed to remove '%s': %s", LevelDir, Ec.message().c_str());
}

