static xr_string FormatNumber(float Value)
{
	string64 Buffer;
	if (std::abs(Value - std::round(Value)) < 0.005f)
	{
		xr_sprintf(Buffer, "%d", (int)std::round(Value));
	}
	else
	{
		xr_sprintf(Buffer, "%.2f", Value);
		// Trailing zeros: 1.50 -> 1.5
		size_t Length = xr_strlen(Buffer);
		while (Length > 0 && Buffer[Length - 1] == '0')
		{
			Buffer[--Length] = 0;
		}
	}
	return Buffer;
}

static xr_string EscapeXml(const xr_string& Text)
{
	xr_string Result;
	Result.reserve(Text.size());
	for (char Char : Text)
	{
		switch (Char)
		{
		case '&':	Result += "&amp;"; break;
		case '<':	Result += "&lt;"; break;
		case '>':	Result += "&gt;"; break;
		case '"':	Result += "&quot;"; break;
		default:	Result += Char; break;
		}
	}
	return Result;
}

// my_btn_ok -> MyBtnOk
static xr_string ToPascalCase(const xr_string& Text)
{
	xr_string Result;
	bool Upper = true;
	for (char Char : Text)
	{
		if (Char == '_')
		{
			Upper = true;
			continue;
		}

		Result += Upper ? (char)toupper((u8)Char) : Char;
		Upper = false;
	}
	return Result;
}

static bool ReadTextFile(const char* Alias, const char* FileName, xr_string& Out)
{
	if (!FS.exist(Alias, FileName))
	{
		return false;
	}

	IReader* Reader = FS.r_open(Alias, FileName);
	if (Reader == nullptr)
	{
		return false;
	}

	Out.assign((const char*)Reader->pointer(), Reader->length());
	FS.r_close(Reader);
	return true;
}

static bool WriteTextFile(const char* Alias, const char* FileName, const xr_string& Text)
{
	IWriter* Writer = FS.w_open(Alias, FileName);
	if (Writer == nullptr)
	{
		return false;
	}

	Writer->w(Text.data(), Text.size());
	FS.w_close(Writer);
	return true;
}

