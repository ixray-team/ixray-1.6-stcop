	int FindEvent(ELayoutWidget Type, const char* Event)
	{
		const std::span<const SLayoutEventInfo> Events = GetEvents(Type);
		for (u32 Index = 0; Index < Events.size(); ++Index)
		{
			if (xr_strcmp(Events[Index].Event, Event) == 0)
			{
				return (int)Index;
			}
		}
		return -1;
	}

