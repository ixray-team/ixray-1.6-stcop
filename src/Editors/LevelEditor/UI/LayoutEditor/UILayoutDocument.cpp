SLayoutWidget& CUILayoutDocument::Add(const SLayoutWidget& Source, u32 Parent)
{
	SLayoutWidget& Widget = Widgets.emplace_back(Source);
	Widget.Id = NextId++;
	Widget.ParentId = Find(Parent) != nullptr ? Parent : 0;
	Widget.Name = MakeUniqueName(Source.Name.empty() ? LayoutWidget::GetDefaultName(Source.Type) : Source.Name.c_str(), Widget.Id);
	return Widget;
}

void CUILayoutDocument::Remove(u32 Id)
{
	xr_vector<u32> Removed = { Id };
	for (size_t Index = 0; Index < Removed.size(); ++Index)
	{
		for (const SLayoutWidget& Widget : Widgets)
		{
			if (Widget.ParentId == Removed[Index])
			{
				Removed.push_back(Widget.Id);
			}
		}
	}

	std::erase_if(Widgets, [&Removed](const SLayoutWidget& Widget)
	{
		return std::find(Removed.begin(), Removed.end(), Widget.Id) != Removed.end();
	});
}

u32 CUILayoutDocument::Duplicate(u32 Id)
{
	const SLayoutWidget* Source = Find(Id);
	if (Source == nullptr)
	{
		return 0;
	}

	// Copy the subtree first: Add reallocates the widget array
	xr_vector<SLayoutWidget> Subtree = { *Source };
	for (size_t Index = 0; Index < Subtree.size(); ++Index)
	{
		for (const SLayoutWidget& Widget : Widgets)
		{
			if (Widget.ParentId == Subtree[Index].Id)
			{
				Subtree.push_back(Widget);
			}
		}
	}

	xr_hash_map<u32, u32> NewIds;
	u32 RootCopy = 0;
	for (SLayoutWidget& Widget : Subtree)
	{
		const u32 OldId = Widget.Id;
		const bool IsRoot = OldId == Id;
		const u32 Parent = IsRoot ? Widget.ParentId : NewIds[Widget.ParentId];
		if (IsRoot)
		{
			Widget.Pos.add(Fvector2{ 10.0f, 10.0f });
		}

		SLayoutWidget& Copy = Add(Widget, Parent);
		NewIds[OldId] = Copy.Id;
		if (IsRoot)
		{
			RootCopy = Copy.Id;
		}
	}
	return RootCopy;
}

bool CUILayoutDocument::Reparent(u32 Id, u32 NewParent)
{
	SLayoutWidget* Widget = Find(Id);
	if (Widget == nullptr || Id == NewParent || IsAncestor(Id, NewParent))
	{
		return false;
	}

	const Fvector2 AbsPos = GetAbsPos(Id);
	const Fvector2 ParentPos = NewParent != 0 ? GetAbsPos(NewParent) : Fvector2{ 0.0f, 0.0f };
	Widget->ParentId = NewParent;
	Widget->Pos = { AbsPos.x - ParentPos.x, AbsPos.y - ParentPos.y };
	return true;
}

bool CUILayoutDocument::MoveSibling(u32 Id, int Direction)
{
	auto It = std::find_if(Widgets.begin(), Widgets.end(), [Id](const SLayoutWidget& Widget) { return Widget.Id == Id; });
	if (It == Widgets.end())
	{
		return false;
	}

	const u32 Parent = It->ParentId;
	if (Direction < 0)
	{
		for (auto Other = std::make_reverse_iterator(It); Other != Widgets.rend(); ++Other)
		{
			if (Other->ParentId == Parent)
			{
				std::iter_swap(It, Other);
				return true;
			}
		}
	}
	else
	{
		for (auto Other = std::next(It); Other != Widgets.end(); ++Other)
		{
			if (Other->ParentId == Parent)
			{
				std::iter_swap(It, Other);
				return true;
			}
		}
	}
	return false;
}

bool CUILayoutDocument::IsAncestor(u32 Ancestor, u32 Id) const
{
	const SLayoutWidget* Widget = Find(Id);
	while (Widget != nullptr && Widget->ParentId != 0)
	{
		if (Widget->ParentId == Ancestor)
		{
			return true;
		}
		Widget = Find(Widget->ParentId);
	}
	return false;
}

Fvector2 CUILayoutDocument::GetAbsPos(u32 Id) const
{
	Fvector2 Result = { 0.0f, 0.0f };
	const SLayoutWidget* Widget = Find(Id);
	// Depth guard against a broken parent chain
	for (int Depth = 0; Widget != nullptr && Depth < 256; ++Depth)
	{
		Result.add(Widget->Pos);
		Widget = Widget->ParentId != 0 ? Find(Widget->ParentId) : nullptr;
	}
	return Result;
}

xr_string CUILayoutDocument::MakeUniqueName(const char* Base, u32 IgnoreId) const
{
	auto IsUsed = [this, IgnoreId](const xr_string& Candidate)
	{
		for (const SLayoutWidget& Widget : Widgets)
		{
			if (Widget.Id != IgnoreId && Widget.Name == Candidate)
			{
				return true;
			}
		}
		return false;
	};

	xr_string Candidate = Base;
	if (!IsUsed(Candidate))
	{
		return Candidate;
	}

	// btn_2 -> btn
	xr_string Stem = Candidate;
	const size_t Underscore = Stem.find_last_of('_');
	if (Underscore != xr_string::npos && Underscore + 1 < Stem.size() && std::all_of(Stem.begin() + Underscore + 1, Stem.end(), ::isdigit))
	{
		Stem.resize(Underscore);
	}

	for (int Index = 1;; ++Index)
	{
		Candidate = Stem + "_" + xr_string::ToString(Index);
		if (!IsUsed(Candidate))
		{
			return Candidate;
		}
	}
}

bool CUILayoutDocument::IsValidName(const char* WidgetName) const
{
	if (WidgetName == nullptr || WidgetName[0] == 0 || isdigit((u8)WidgetName[0]))
	{
		return false;
	}

	for (const char* Char = WidgetName; *Char != 0; ++Char)
	{
		if (!isalnum((u8)*Char) && *Char != '_')
		{
			return false;
		}
	}
	return true;
}

xr_vector<u32> CUILayoutDocument::GetOrdered() const
{
	xr_vector<u32> Result;
	Result.reserve(Widgets.size());

	auto Visit = [this, &Result](auto&& Self, u32 Parent) -> void
	{
		for (const SLayoutWidget& Widget : Widgets)
		{
			if (Widget.ParentId == Parent)
			{
				Result.push_back(Widget.Id);
				Self(Self, Widget.Id);
			}
		}
	};
	Visit(Visit, 0);

	return Result;
}

xr_string CUILayoutDocument::GetClassName() const
{
	xr_string Result = Name;
	if (Result.starts_with("ui_") && Result.size() > 3)
	{
		Result.erase(0, 3);
	}
	return Result;
}

xr_string CUILayoutDocument::GetDefaultHandlerName(const SLayoutWidget& Widget, u32 EventIndex) const
{
	const std::span<const SLayoutEventInfo> Events = LayoutWidget::GetEvents(Widget.Type);
	return "On" + ToPascalCase(Widget.Name) + (EventIndex < Events.size() ? Events[EventIndex].Suffix : "");
}

xr_string CUILayoutDocument::GetHandlerName(const SLayoutWidget& Widget, u32 EventIndex) const
{
	const xr_string& Handler = Widget.Events[EventIndex].Handler;
	return Handler.empty() ? GetDefaultHandlerName(Widget, EventIndex) : Handler;
}

xr_string CUILayoutDocument::GetVarName(u32 Id) const
{
	const SLayoutWidget* Widget = Find(Id);
	return Widget != nullptr ? "self." + Widget->Name : "self";
}

xr_string CUILayoutDocument::BuildXml(bool Wide) const
{
	xr_string Out = "<w>\n";

	for (u32 Id : GetOrdered())
	{
		const SLayoutWidget& Widget = *Find(Id);

		Fvector2 Pos = Widget.Pos;
		Fvector2 Size = Widget.Size;
		bool Stretch = Widget.Stretch;
		if (Wide)
		{
			// Dialog children are centered on the wide screen, the rest keeps the parent offset
			Pos.x = Widget.ParentId == 0 ? Pos.x * WideScale + ScreenWidth * (1.0f - WideScale) * 0.5f : Pos.x * WideScale;
			Pos.x = std::floor(Pos.x);
			Size.x = std::floor(Size.x * WideScale);
			Stretch |= !Widget.Texture.empty() && LayoutWidget::HasTexture(Widget.Type);
		}

		Out += "\t<" + Widget.Name;
		Out += " x=\"" + FormatNumber(Pos.x) + "\" y=\"" + FormatNumber(Pos.y) + "\"";
		Out += " width=\"" + FormatNumber(Size.x) + "\" height=\"" + FormatNumber(Size.y) + "\"";
		if (Stretch && Widget.Type != ELayoutWidget::ProgressBar)
		{
			Out += " stretch=\"1\"";
		}

		switch (Widget.Type)
		{
		case ELayoutWidget::Static:
		case ELayoutWidget::TextWnd:
			Out += " complex_mode=\"0\"";
			break;
		case ELayoutWidget::Button:
		case ELayoutWidget::Check:
			Out += " check_mode=\"0\"";
			break;
		case ELayoutWidget::TrackBar:
			Out += xr_string(" is_integer=\"") + (Widget.IsInteger ? "1" : "0") + "\"";
			Out += " min=\"" + FormatNumber(Widget.Min) + "\" max=\"" + FormatNumber(Widget.Max) + "\" step=\"" + FormatNumber(Widget.Step) + "\"";
			break;
		case ELayoutWidget::ProgressBar:
			Out += xr_string(" horz=\"") + (Widget.Horizontal ? "1" : "0") + "\"";
			Out += " min=\"" + FormatNumber(Widget.Min) + "\" max=\"" + FormatNumber(Widget.Max) + "\" pos=\"" + FormatNumber(Widget.Value) + "\"";
			break;
		case ELayoutWidget::ListBox:
		case ELayoutWidget::ListWnd:
			Out += " item_height=\"" + FormatNumber(Widget.ItemHeight) + "\"";
			break;
		case ELayoutWidget::FrameLine:
			Out += xr_string(" vertical=\"") + (Widget.Horizontal ? "0" : "1") + "\"";
			break;
		case ELayoutWidget::SpinNum:
		case ELayoutWidget::SpinFloat:
		case ELayoutWidget::SpinText:
			Out += xr_string(" horz=\"") + (Widget.Horizontal ? "1" : "0") + "\"";
			break;
		case ELayoutWidget::ArrowStepper:
			Out += xr_string(" mode=\"") + (Widget.IsInteger ? "integer" : "float") + "\" step=\"" + FormatNumber(Widget.Step) + "\"";
			break;
		case ELayoutWidget::ScrollView:
			Out += " always_show_scroll=\"0\"";
			break;
		default:
			break;
		}

		xr_string Body;
		if (Widget.Type == ELayoutWidget::ProgressBar)
		{
			Body += xr_string("\t\t<progress") + (Stretch ? " stretch=\"1\"" : "") + ">\n";
			Body += "\t\t\t<texture>" + EscapeXml(Widget.Texture) + "</texture>\n";
			Body += "\t\t</progress>\n";
		}
		else if (LayoutWidget::HasTexture(Widget.Type) && !Widget.Texture.empty())
		{
			Body += "\t\t<texture>" + EscapeXml(Widget.Texture) + "</texture>\n";
		}

		if (LayoutWidget::HasText(Widget.Type) && (!Widget.Text.empty() || Widget.Type == ELayoutWidget::TextWnd || Widget.Type == ELayoutWidget::EditBox))
		{
			const char* Tag = Widget.Type == ELayoutWidget::ListBox || Widget.Type == ELayoutWidget::ListWnd ? "font" : Widget.Type == ELayoutWidget::ComboBox ? "list_font" : "text";
			static constexpr const char* AlignNames[] = { "l", "c", "r" };
			static constexpr const char* VertAlignNames[] = { "t", "c", "b" };

			Body += xr_string("\t\t<") + Tag;
			if (Widget.Type != ELayoutWidget::ListBox && Widget.Type != ELayoutWidget::ListWnd && Widget.Type != ELayoutWidget::ComboBox)
			{
				Body += xr_string(" align=\"") + AlignNames[(int)Widget.Align] + "\" vert_align=\"" + VertAlignNames[(int)Widget.VertAlign] + "\"";
			}
			Body += " font=\"" + Widget.Font + "\"";
			Body += " r=\"" + xr_string::ToString(color_get_R(Widget.TextColor)) + "\"";
			Body += " g=\"" + xr_string::ToString(color_get_G(Widget.TextColor)) + "\"";
			Body += " b=\"" + xr_string::ToString(color_get_B(Widget.TextColor)) + "\"";
			if (color_get_A(Widget.TextColor) != 255)
			{
				Body += " a=\"" + xr_string::ToString(color_get_A(Widget.TextColor)) + "\"";
			}

			const bool HasContent = Tag[0] == 't' && !Widget.Text.empty();
			Body += HasContent ? ">" + EscapeXml(Widget.Text) + "</" + Tag + ">\n" : "/>\n";
		}

		if (LayoutWidget::HasOptions(Widget.Type) && !Widget.OptionsEntry.empty())
		{
			Body += "\t\t<options_item entry=\"" + EscapeXml(Widget.OptionsEntry) + "\" group=\"" + EscapeXml(Widget.OptionsGroup) + "\"/>\n";
		}

		Out += Body.empty() ? "/>\n\n" : ">\n" + Body + "\t</" + Widget.Name + ">\n\n";
	}

	Out += "</w>\n";
	return Out;
}

static xr_string BuildGeneratedRegion(const CUILayoutDocument& Doc)
{
	const xr_string Class = Doc.GetClassName();
	xr_string Out = xr_string(GeneratedBegin) + "\n";

	Out += "function " + Class + ":InitControls()\n";
	Out += "\tlocal xml = CScriptXmlInit()\n";
	Out += "\txml:ParseFile(\"" + Doc.Name + ".xml\")\n\n";

	xr_string Callbacks;
	for (u32 Id : Doc.GetOrdered())
	{
		const SLayoutWidget& Widget = *Doc.Find(Id);
		const xr_string Var = "self." + Widget.Name;
		const xr_string Parent = Doc.GetVarName(Widget.ParentId);

		if (Widget.Type == ELayoutWidget::Window)
		{
			Out += "\t" + Var + " = CUIWindow()\n";
			Out += "\txml:InitWindow(\"" + Widget.Name + "\", 0, " + Var + ")\n";
			Out += "\t" + Var + ":SetAutoDelete(true)\n";
			Out += "\t" + Parent + ":AttachChild(" + Var + ")\n";
		}
		else
		{
			Out += "\t" + Var + " = xml:" + LayoutWidget::GetInitFunction(Widget.Type) + "(\"" + Widget.Name + "\", " + Parent + ")\n";
		}

		if (LayoutWidget::HasEnabledEvents(Widget))
		{
			Out += "\tself:Register(" + Var + ", \"" + Widget.Name + "\")\n";
		}

		const std::span<const SLayoutEventInfo> Events = LayoutWidget::GetEvents(Widget.Type);
		for (u32 Index = 0; Index < Events.size(); ++Index)
		{
			if (Widget.Events[Index].Enabled)
			{
				Callbacks += "\tself:AddCallback(\"" + Widget.Name + "\", ui_events." + Events[Index].Event + ", self." + Doc.GetHandlerName(Widget, Index) + ", self)\n";
			}
		}
	}
	Out += "end\n\n";

	Out += "function " + Class + ":InitCallbacks()\n";
	Out += Callbacks;
	Out += "end\n";
	Out += xr_string(GeneratedEnd) + "\n";
	return Out;
}

static xr_string BuildHandler(const CUILayoutDocument& Doc, const xr_string& Handler)
{
	return "function " + Doc.GetClassName() + ":" + Handler + "()\nend\n\n";
}

// Handlers of every enabled event, each name once: several events may share one handler
static xr_vector<xr_string> GetHandlers(const CUILayoutDocument& Doc)
{
	xr_vector<xr_string> Handlers;
	for (u32 Id : Doc.GetOrdered())
	{
		const SLayoutWidget& Widget = *Doc.Find(Id);
		for (u32 Index = 0; Index < LayoutWidget::GetEvents(Widget.Type).size(); ++Index)
		{
			const xr_string Handler = Doc.GetHandlerName(Widget, Index);
			if (Widget.Events[Index].Enabled && std::find(Handlers.begin(), Handlers.end(), Handler) == Handlers.end())
			{
				Handlers.push_back(Handler);
			}
		}
	}
	return Handlers;
}

xr_string CUILayoutDocument::BuildScript() const
{
	const xr_string Class = GetClassName();
	xr_string Out;

	Out += "-- " + Name + ".script\n";
	Out += "-- Layout: configs\\ui\\" + Name + ".xml (" + Name + "_16.xml on widescreen)\n";
	Out += "-- Show it with " + Name + ".Show()\n\n";

	Out += "local dialog = nil\n\n";

	Out += "class \"" + Class + "\" (CUIScriptWnd)\n\n";

	Out += "function " + Class + ":__init() super()\n";
	Out += "\tself:SetWndRect(Frect():set(0, 0, 1024, 768))\n";
	Out += "\tself:InitControls()\n";
	Out += "\tself:InitCallbacks()\n";
	Out += "end\n\n";

	Out += "function " + Class + ":__finalize()\n";
	Out += "end\n\n";

	Out += BuildGeneratedRegion(*this) + "\n";

	for (const xr_string& Handler : GetHandlers(*this))
	{
		Out += BuildHandler(*this, Handler);
	}

	Out += "function " + Class + ":OnKeyboard(dik, keyboard_action)\n";
	Out += "\tlocal res = CUIScriptWnd.OnKeyboard(self, dik, keyboard_action)\n";
	Out += "\tif res == false and keyboard_action == ui_events.WINDOW_KEY_PRESSED then\n";
	Out += "\t\tif dik == DIK_keys.DIK_ESCAPE then\n";
	Out += "\t\t\tself:HideDialog()\n";
	Out += "\t\t\tres = true\n";
	Out += "\t\tend\n";
	Out += "\tend\n";
	Out += "\treturn res\n";
	Out += "end\n\n";

	// Entry point: the Level Editor calls it when the widget is dropped on the scene in PIE
	Out += "function Show()\n";
	Out += "\tif dialog == nil then\n";
	Out += "\t\tdialog = " + Class + "()\n";
	Out += "\tend\n";
	Out += "\tdialog:ShowDialog(true)\n";
	Out += "\treturn dialog\n";
	Out += "end\n";

	return Out;
}

bool CUILayoutDocument::MergeScript(const xr_string& Existing, xr_string& Out) const
{
	const size_t Begin = Existing.find(GeneratedBegin);
	const size_t End = Begin != xr_string::npos ? Existing.find(GeneratedEnd, Begin) : xr_string::npos;
	if (End == xr_string::npos)
	{
		return false;
	}

	size_t EndLine = Existing.find('\n', End);
	EndLine = EndLine == xr_string::npos ? Existing.size() : EndLine + 1;

	Out = Existing.substr(0, Begin) + BuildGeneratedRegion(*this) + Existing.substr(EndLine);

	// User code keeps its handlers, new callbacks get empty ones at the end
	const xr_string Class = GetClassName();
	xr_string Missing;
	for (const xr_string& Handler : GetHandlers(*this))
	{
		if (Out.find("function " + Class + ":" + Handler + "(") == xr_string::npos)
		{
			Missing += BuildHandler(*this, Handler);
		}
	}

	if (!Missing.empty())
	{
		if (!Out.ends_with("\n"))
		{
			Out += "\n";
		}
		Out += "\n" + Missing;
	}
	return true;
}

static xr_string ToCRLF(const xr_string& Text)
{
	xr_string Result;
	Result.reserve(Text.size() + Text.size() / 16);
	for (size_t Index = 0; Index < Text.size(); ++Index)
	{
		if (Text[Index] == '\n' && (Index == 0 || Text[Index - 1] != '\r'))
		{
			Result += '\r';
		}
		Result += Text[Index];
	}
	return Result;
}

static xr_string FromCRLF(const xr_string& Text)
{
	xr_string Result = Text;
	std::erase(Result, '\r');
	return Result;
}

bool CUILayoutDocument::Save(const xr_string& Source, xr_string& Error) const
{
	if (!IsValidName(Name.c_str()))
	{
		Error = "Layout name must contain only latin letters, digits and '_'";
		return false;
	}

	for (const SLayoutWidget& Widget : Widgets)
	{
		if (!IsValidName(Widget.Name.c_str()))
		{
			Error = "Invalid widget name: " + Widget.Name;
			return false;
		}
	}

	const xr_string ScriptFile = Name + ".script";
	xr_string Script;
	if (Source.empty())
	{
		Script = BuildScript();
	}
	else if (!MergeScript(Source, Script))
	{
		Error = ScriptFile + " has no ui_layout markers, the layout can't update it";
		return false;
	}

	const xr_string XmlFile = "ui\\" + Name + ".xml";
	const xr_string WideXmlFile = "ui\\" + Name + "_16.xml";
	if (!WriteTextFile(_game_config_, XmlFile.c_str(), ToCRLF(ToGameText(BuildXml(false))))
		|| !WriteTextFile(_game_config_, WideXmlFile.c_str(), ToCRLF(ToGameText(BuildXml(true))))
		|| !WriteTextFile("$game_scripts$", ScriptFile.c_str(), ToCRLF(ToGameText(Script))))
	{
		Error = "Can't write the layout files";
		return false;
	}

	CXml::RemoveFromCache(_game_config_, XmlFile.c_str());
	CXml::RemoveFromCache(_game_config_, WideXmlFile.c_str());
	return true;
}

static ELayoutWidget GuessType(tinyxml2::XMLElement* Node)
{
	const char* Texture = Node->FirstChildElement("texture") != nullptr ? Node->FirstChildElement("texture")->GetText() : nullptr;

	if (Node->FirstChildElement("progress") != nullptr)
	{
		return ELayoutWidget::ProgressBar;
	}
	if (Node->FirstChildElement("list_font") != nullptr)
	{
		return ELayoutWidget::ComboBox;
	}
	if (Node->Attribute("item_height") != nullptr)
	{
		return ELayoutWidget::ListBox;
	}
	if (Node->Attribute("check_mode") != nullptr || Node->FirstChildElement("window_name") != nullptr)
	{
		return Texture != nullptr && strstr(Texture, "checkbox") != nullptr ? ELayoutWidget::Check : ELayoutWidget::Button;
	}
	if (Node->Attribute("is_integer") != nullptr || Node->Attribute("step") != nullptr)
	{
		return ELayoutWidget::TrackBar;
	}
	if (Node->Attribute("always_show_scroll") != nullptr)
	{
		return ELayoutWidget::ScrollView;
	}
	if (Texture != nullptr || Node->FirstChildElement("text") != nullptr)
	{
		return ELayoutWidget::Static;
	}
	return ELayoutWidget::Window;
}

// Geometry, texture, text and options of a widget node. The type must be set: it picks the range defaults
static void ReadWidgetNode(tinyxml2::XMLElement* Node, SLayoutWidget& Widget)
{
	Widget.Pos = { Node->FloatAttribute("x"), Node->FloatAttribute("y") };
	Widget.Size = { Node->FloatAttribute("width"), Node->FloatAttribute("height") };
	Widget.Stretch = Node->IntAttribute("stretch") != 0;
	Widget.IsInteger = Node->IntAttribute("is_integer") != 0;
	Widget.Min = Node->FloatAttribute("min", 0.0f);
	Widget.Max = Node->FloatAttribute("max", Widget.Type == ELayoutWidget::ProgressBar ? 1.0f : 100.0f);
	Widget.Step = Node->FloatAttribute("step", 1.0f);
	Widget.Value = Node->FloatAttribute("pos", 0.0f);
	Widget.Horizontal = Node->IntAttribute("horz", 1) != 0 && Node->IntAttribute("vertical", 0) == 0;
	if (const char* Mode = Node->Attribute("mode"))
	{
		Widget.IsInteger = xr_strcmp(Mode, "integer") == 0;
	}
	Widget.ItemHeight = Node->FloatAttribute("item_height", 20.0f);

	tinyxml2::XMLElement* TextureNode = Node->FirstChildElement("texture");
	if (tinyxml2::XMLElement* Progress = Node->FirstChildElement("progress"))
	{
		TextureNode = Progress->FirstChildElement("texture");
		Widget.Stretch |= Progress->IntAttribute("stretch") != 0;
	}
	if (TextureNode != nullptr && TextureNode->GetText() != nullptr)
	{
		Widget.Texture = TextureNode->GetText();
	}

	tinyxml2::XMLElement* TextNode = Node->FirstChildElement("text");
	if (TextNode == nullptr)
	{
		TextNode = Node->FirstChildElement("font");
	}
	if (TextNode == nullptr)
	{
		TextNode = Node->FirstChildElement("list_font");
	}
	if (TextNode != nullptr)
	{
		Widget.Text = FromGameText(TextNode->GetText());
		if (const char* Font = TextNode->Attribute("font"))
		{
			Widget.Font = Font;
		}
		Widget.TextColor = color_rgba(TextNode->IntAttribute("r", 255), TextNode->IntAttribute("g", 255), TextNode->IntAttribute("b", 255), TextNode->IntAttribute("a", 255));

		const char* Align = TextNode->Attribute("align", nullptr);
		Widget.Align = Align == nullptr ? ELayoutAlign::Left : Align[0] == 'c' ? ELayoutAlign::Center : Align[0] == 'r' ? ELayoutAlign::Right : ELayoutAlign::Left;
		const char* VertAlign = TextNode->Attribute("vert_align", nullptr);
		Widget.VertAlign = VertAlign == nullptr ? ELayoutVertAlign::Top : VertAlign[0] == 'c' ? ELayoutVertAlign::Center : VertAlign[0] == 'b' ? ELayoutVertAlign::Bottom : ELayoutVertAlign::Top;
	}

	if (tinyxml2::XMLElement* Options = Node->FirstChildElement("options_item"))
	{
		const char* Entry = Options->Attribute("entry");
		const char* Group = Options->Attribute("group");
		Widget.OptionsEntry = Entry != nullptr ? Entry : "";
		Widget.OptionsGroup = Group != nullptr ? Group : "";
	}
}

bool CUILayoutDocument::ReadScript(const char* LayoutName, xr_string& Out)
{
	xr_string Script;
	if (!ReadTextFile("$game_scripts$", (xr_string(LayoutName) + ".script").c_str(), Script))
	{
		return false;
	}

	Out = FromCRLF(FromGameText(Script.c_str()));
	return true;
}

bool CUILayoutDocument::Load(const char* LayoutName, xr_string& Error)
{
	xr_string XmlText;
	const xr_string XmlFile = xr_string("ui\\") + LayoutName + ".xml";
	if (!ReadTextFile(_game_config_, XmlFile.c_str(), XmlText))
	{
		Error = "Can't read " + XmlFile;
		return false;
	}

	xr_string Script;
	ReadScript(LayoutName, Script);

	CUILayoutDocument Loaded;
	Loaded.Name = LayoutName;
	if (!Loaded.ApplyXml(FromGameText(XmlText.c_str()), Script, Error))
	{
		Error = XmlFile + ": " + Error;
		return false;
	}

	*this = Loaded;
	return true;
}

bool CUILayoutDocument::ApplyXml(const xr_string& XmlText, const xr_string& Script, xr_string& Error)
{
	// The xml is parsed in the game code page, like the engine reads it
	const xr_string GameXml = ToGameText(XmlText);
	tinyxml2::XMLDocument Xml;
	if (Xml.Parse(GameXml.data(), GameXml.size()) != tinyxml2::XML_SUCCESS || Xml.RootElement() == nullptr)
	{
		Error = Xml.ErrorStr() != nullptr ? Xml.ErrorStr() : "Invalid xml";
		return false;
	}

	// The script knows the widget types and parents: self.x = xml:InitStatic("x", self.parent)
	struct SScriptInfo
	{
		ELayoutWidget Type;
		xr_string Parent;
	};
	xr_hash_map<xr_string, SScriptInfo> ScriptInfo;
	struct SScriptCallback
	{
		xr_string Event;
		xr_string Handler;
	};
	xr_hash_map<xr_string, xr_vector<SScriptCallback>> Registered;

	if (!Script.empty())
	{
		// Variable names may differ from the xml names: self.back = xml:InitStatic("background", self)
		static const std::regex InitCall(R"((?:self\.(\w+)\s*=\s*)?xml:(Init\w+)\s*\(\s*\"([\w:]+)\"\s*,\s*(?:0\s*,\s*)?self(?:\.(\w+))?\s*\))");
		static const std::regex AttachCall(R"(self(?:\.(\w+))?:AttachChild\s*\(\s*self\.(\w+)\s*\))");
		static const std::regex Callback(R"(AddCallback\s*\(\s*\"(\w+)\"\s*,\s*ui_events\.(\w+)\s*,\s*self\.(\w+))");

		xr_hash_map<xr_string, xr_string> VarToName;
		const std::string Source(Script.c_str());
		for (std::sregex_iterator It(Source.begin(), Source.end(), InitCall), End; It != End; ++It)
		{
			const std::string Function = (*It)[2];
			const xr_string WidgetName = (*It)[3].str().c_str();
			if ((*It)[1].matched)
			{
				VarToName[(*It)[1].str().c_str()] = WidgetName;
			}

			for (int Type = 0; Type < (int)ELayoutWidget::Count; ++Type)
			{
				if (Function == LayoutWidget::GetInitFunction((ELayoutWidget)Type))
				{
					ScriptInfo[WidgetName] = { (ELayoutWidget)Type, (*It)[4].str().c_str() };
					break;
				}
			}
		}

		// InitWindow takes the window itself, its parent comes from AttachChild
		for (std::sregex_iterator It(Source.begin(), Source.end(), AttachCall), End; It != End; ++It)
		{
			auto Child = VarToName.find((*It)[2].str().c_str());
			auto Info = ScriptInfo.find(Child != VarToName.end() ? Child->second : xr_string((*It)[2].str().c_str()));
			if (Info != ScriptInfo.end())
			{
				Info->second.Parent = (*It)[1].str().c_str();
			}
		}

		for (auto& [WidgetName, Info] : ScriptInfo)
		{
			auto Parent = VarToName.find(Info.Parent);
			if (Parent != VarToName.end())
			{
				Info.Parent = Parent->second;
			}
		}

		for (std::sregex_iterator It(Source.begin(), Source.end(), Callback), End; It != End; ++It)
		{
			Registered[(*It)[1].str().c_str()].push_back({ (*It)[2].str().c_str(), (*It)[3].str().c_str() });
		}
	}

	// Editor only flags survive a reparse
	xr_hash_map<xr_string, std::pair<bool, bool>> EditorFlags;
	for (const SLayoutWidget& Widget : Widgets)
	{
		EditorFlags[Widget.Name] = { Widget.Hidden, Widget.Locked };
	}

	Clear();

	xr_vector<std::pair<u32, xr_string>> Parents;
	for (tinyxml2::XMLElement* Node = Xml.RootElement()->FirstChildElement(); Node != nullptr; Node = Node->NextSiblingElement())
	{
		if (Node->Attribute("x") == nullptr && Node->Attribute("width") == nullptr)
		{
			continue;
		}

		SLayoutWidget Widget;
		Widget.Name = Node->Name();
		auto Info = ScriptInfo.find(Widget.Name);
		Widget.Type = Info != ScriptInfo.end() ? Info->second.Type : GuessType(Node);

		auto Callbacks = Registered.find(Widget.Name);
		if (Callbacks != Registered.end())
		{
			for (const SScriptCallback& Callback : Callbacks->second)
			{
				const int Index = LayoutWidget::FindEvent(Widget.Type, Callback.Event.c_str());
				if (Index < 0)
				{
					continue;
				}

				Widget.Events[Index].Enabled = true;
				if (Callback.Handler != GetDefaultHandlerName(Widget, Index))
				{
					Widget.Events[Index].Handler = Callback.Handler;
				}
			}
		}

		auto Flags = EditorFlags.find(Widget.Name);
		if (Flags != EditorFlags.end())
		{
			Widget.Hidden = Flags->second.first;
			Widget.Locked = Flags->second.second;
		}

		ReadWidgetNode(Node, Widget);

		// Names of the stock files are unique, Add keeps them
		const u32 Id = Add(Widget, 0).Id;
		if (Info != ScriptInfo.end() && !Info->second.Parent.empty())
		{
			Parents.emplace_back(Id, Info->second.Parent);
		}
	}

	for (const auto& [Id, ParentName] : Parents)
	{
		SLayoutWidget* Parent = FindByName(ParentName.c_str());
		if (Parent != nullptr && Parent->Id != Id && !IsAncestor(Id, Parent->Id))
		{
			Find(Id)->ParentId = Parent->Id;
		}
	}

	return true;
}

static const char* WidgetsAlias = "$server_data_root$";

static xr_string GetWidgetFile(const char* LayoutName)
{
	return xr_string("widgets\\") + LayoutName + CUILayoutDocument::WidgetExt;
}

bool CUILayoutDocument::WidgetExists(const char* LayoutName)
{
	return FS.path_exist(WidgetsAlias) && FS.exist(WidgetsAlias, GetWidgetFile(LayoutName).c_str());
}

void CUILayoutDocument::ListWidgets(xr_vector<xr_string>& Out)
{
	if (!FS.path_exist(WidgetsAlias))
	{
		return;
	}

	string_path Dir;
	FS.update_path(Dir, WidgetsAlias, "widgets\\");

	std::error_code Code;
	for (const auto& Entry : std::filesystem::directory_iterator(Dir, Code))
	{
		if (Entry.is_regular_file() && Entry.path().extension() == WidgetExt)
		{
			Out.push_back(Entry.path().stem().string().c_str());
		}
	}
}

bool CUILayoutDocument::SaveWidget(xr_string& Error) const
{
	if (!FS.path_exist(WidgetsAlias))
	{
		Error = "No $server_data_root$ path for rawdata\widgets";
		return false;
	}

	nlohmann::json Data;
	Data["name"] = Name.c_str();
	Data["next_id"] = NextId;

	nlohmann::json& List = Data["widgets"];
	List = nlohmann::json::array();
	for (const SLayoutWidget& Widget : Widgets)
	{
		nlohmann::json Item;
		Item["id"] = Widget.Id;
		Item["parent"] = Widget.ParentId;
		Item["type"] = LayoutWidget::GetTypeName(Widget.Type);
		Item["name"] = Widget.Name.c_str();
		Item["pos"] = { Widget.Pos.x, Widget.Pos.y };
		Item["size"] = { Widget.Size.x, Widget.Size.y };
		Item["texture"] = Widget.Texture.c_str();
		Item["stretch"] = Widget.Stretch;
		Item["text"] = Widget.Text.c_str();
		Item["font"] = Widget.Font.c_str();
		Item["text_color"] = Widget.TextColor;
		Item["align"] = (int)Widget.Align;
		Item["vert_align"] = (int)Widget.VertAlign;
		Item["min"] = Widget.Min;
		Item["max"] = Widget.Max;
		Item["value"] = Widget.Value;
		Item["step"] = Widget.Step;
		Item["is_integer"] = Widget.IsInteger;
		Item["horizontal"] = Widget.Horizontal;
		Item["item_height"] = Widget.ItemHeight;
		Item["options_entry"] = Widget.OptionsEntry.c_str();
		Item["options_group"] = Widget.OptionsGroup.c_str();
		Item["hidden"] = Widget.Hidden;
		Item["locked"] = Widget.Locked;

		nlohmann::json& Events = Item["events"];
		Events = nlohmann::json::array();
		const std::span<const SLayoutEventInfo> Infos = LayoutWidget::GetEvents(Widget.Type);
		for (u32 Index = 0; Index < Infos.size(); ++Index)
		{
			if (Widget.Events[Index].Enabled)
			{
				Events.push_back({ { "event", Infos[Index].Event }, { "handler", Widget.Events[Index].Handler.c_str() } });
			}
		}

		List.push_back(Item);
	}

	if (!WriteTextFile(WidgetsAlias, GetWidgetFile(Name.c_str()).c_str(), ToCRLF(Data.dump(1, '\t').c_str())))
	{
		Error = "Can't write rawdata\\" + GetWidgetFile(Name.c_str());
		return false;
	}
	return true;
}

template <typename T>
static T ReadJson(const nlohmann::json& Data, const char* Key, const T& Default)
{
	auto It = Data.find(Key);
	if (It == Data.end())
	{
		return Default;
	}

	try
	{
		return It->get<T>();
	}
	catch (...)
	{
		return Default;
	}
}

static xr_string ReadJsonString(const nlohmann::json& Data, const char* Key, const char* Default = "")
{
	return ReadJson<std::string>(Data, Key, Default).c_str();
}

static Fvector2 ReadJsonVector(const nlohmann::json& Data, const char* Key, const Fvector2& Default)
{
	auto It = Data.find(Key);
	if (It == Data.end() || !It->is_array() || It->size() != 2 || !(*It)[0].is_number() || !(*It)[1].is_number())
	{
		return Default;
	}
	return { (*It)[0].get<float>(), (*It)[1].get<float>() };
}

bool CUILayoutDocument::LoadWidget(const char* LayoutName, xr_string& Error)
{
	const xr_string File = GetWidgetFile(LayoutName);
	xr_string Text;
	if (!FS.path_exist(WidgetsAlias) || !ReadTextFile(WidgetsAlias, File.c_str(), Text))
	{
		Error = "Can't read rawdata\\" + File;
		return false;
	}

	const nlohmann::json Data = nlohmann::json::parse(Text.c_str(), nullptr, false);
	if (Data.is_discarded() || !Data.is_object() || !Data.contains("widgets") || !Data["widgets"].is_array())
	{
		Error = "rawdata\\" + File + ": invalid widget file";
		return false;
	}

	CUILayoutDocument Loaded;
	Loaded.Name = LayoutName;
	const SLayoutWidget Defaults;
	for (const nlohmann::json& Item : Data["widgets"])
	{
		if (!Item.is_object())
		{
			continue;
		}

		SLayoutWidget Widget;
		Widget.Id = ReadJson<u32>(Item, "id", 0);
		Widget.ParentId = ReadJson<u32>(Item, "parent", 0);
		Widget.Name = ReadJsonString(Item, "name");

		const xr_string TypeName = ReadJsonString(Item, "type");
		for (int Type = 0; Type < (int)ELayoutWidget::Count; ++Type)
		{
			if (TypeName == LayoutWidget::GetTypeName((ELayoutWidget)Type))
			{
				Widget.Type = (ELayoutWidget)Type;
				break;
			}
		}

		if (Widget.Id == 0 || Loaded.Find(Widget.Id) != nullptr || !IsValidName(Widget.Name.c_str()))
		{
			Error = "rawdata\\" + File + ": invalid widget " + Widget.Name;
			return false;
		}

		Widget.Pos = ReadJsonVector(Item, "pos", Defaults.Pos);
		Widget.Size = ReadJsonVector(Item, "size", Defaults.Size);
		Widget.Texture = ReadJsonString(Item, "texture");
		Widget.Stretch = ReadJson(Item, "stretch", Defaults.Stretch);
		Widget.Text = ReadJsonString(Item, "text");
		Widget.Font = ReadJsonString(Item, "font", Defaults.Font.c_str());
		Widget.TextColor = ReadJson(Item, "text_color", Defaults.TextColor);
		Widget.Align = (ELayoutAlign)std::clamp(ReadJson(Item, "align", (int)Defaults.Align), 0, (int)ELayoutAlign::Right);
		Widget.VertAlign = (ELayoutVertAlign)std::clamp(ReadJson(Item, "vert_align", (int)Defaults.VertAlign), 0, (int)ELayoutVertAlign::Bottom);
		Widget.Min = ReadJson(Item, "min", Defaults.Min);
		Widget.Max = ReadJson(Item, "max", Defaults.Max);
		Widget.Value = ReadJson(Item, "value", Defaults.Value);
		Widget.Step = ReadJson(Item, "step", Defaults.Step);
		Widget.IsInteger = ReadJson(Item, "is_integer", Defaults.IsInteger);
		Widget.Horizontal = ReadJson(Item, "horizontal", Defaults.Horizontal);
		Widget.ItemHeight = ReadJson(Item, "item_height", Defaults.ItemHeight);
		Widget.OptionsEntry = ReadJsonString(Item, "options_entry");
		Widget.OptionsGroup = ReadJsonString(Item, "options_group");
		Widget.Hidden = ReadJson(Item, "hidden", false);
		Widget.Locked = ReadJson(Item, "locked", false);

		auto Events = Item.find("events");
		if (Events != Item.end() && Events->is_array())
		{
			for (const nlohmann::json& Event : *Events)
			{
				const int Index = LayoutWidget::FindEvent(Widget.Type, ReadJsonString(Event, "event").c_str());
				if (Index >= 0)
				{
					Widget.Events[Index].Enabled = true;
					Widget.Events[Index].Handler = ReadJsonString(Event, "handler");
				}
			}
		}

		Loaded.Widgets.push_back(Widget);
		Loaded.NextId = std::max(Loaded.NextId, Widget.Id + 1);
	}

	// A missing or looped parent puts the widget on the dialog
	for (SLayoutWidget& Widget : Loaded.Widgets)
	{
		const SLayoutWidget* Parent = Loaded.Find(Widget.ParentId);
		for (size_t Depth = 0; Parent != nullptr && Parent->ParentId != 0; ++Depth)
		{
			if (Parent->ParentId == Widget.Id || Depth > Loaded.Widgets.size())
			{
				Parent = nullptr;
				break;
			}
			Parent = Loaded.Find(Parent->ParentId);
		}

		if (Widget.ParentId != 0 && (Parent == nullptr || Widget.ParentId == Widget.Id))
		{
			Widget.ParentId = 0;
		}
	}
	Loaded.NextId = std::max(Loaded.NextId, ReadJson<u32>(Data, "next_id", 1));

	*this = Loaded;
	return true;
}

// A node is a widget when it has a rect, its other children are its properties
static bool IsWidgetNode(tinyxml2::XMLElement* Node)
{
	return Node->Attribute("x") != nullptr || Node->Attribute("width") != nullptr;
}

static xr_string ToWidgetName(const char* NodeName)
{
	xr_string Result;
	for (const char* Char = NodeName; *Char != 0; ++Char)
	{
		Result += isalnum((u8)*Char) ? (char)tolower((u8)*Char) : '_';
	}
	if (Result.empty() || isdigit((u8)Result[0]))
	{
		Result = "w_" + Result;
	}
	return Result;
}

static void ImportNode(CUILayoutDocument& Doc, tinyxml2::XMLElement* Parent, u32 ParentId)
{
	for (tinyxml2::XMLElement* Node = Parent->FirstChildElement(); Node != nullptr; Node = Node->NextSiblingElement())
	{
		if (!IsWidgetNode(Node))
		{
			continue;
		}

		SLayoutWidget Widget;
		Widget.Type = GuessType(Node);
		// Stock files reuse names in different branches, the script needs unique ones
		Widget.Name = Doc.MakeUniqueName(ToWidgetName(Node->Name()).c_str());
		ReadWidgetNode(Node, Widget);

		const u32 Id = Doc.Add(Widget, ParentId).Id;
		ImportNode(Doc, Node, Id);
	}
}

bool CUILayoutDocument::Import(const char* FileName, xr_string& Error)
{
	xr_string XmlText;
	if (!ReadTextFile(_game_config_, FileName, XmlText))
	{
		Error = xr_string("Can't read configs\\") + FileName;
		return false;
	}

	tinyxml2::XMLDocument Xml;
	if (Xml.Parse(XmlText.data(), XmlText.size()) != tinyxml2::XML_SUCCESS || Xml.RootElement() == nullptr)
	{
		Error = xr_string(FileName) + ": " + (Xml.ErrorStr() != nullptr ? Xml.ErrorStr() : "invalid xml");
		return false;
	}

	CUILayoutDocument Imported;
	// ui\inventory\ui_inventory.xml -> ui_inventory_import: a new name keeps the stock files intact
	xr_string Stem = xr_path(FileName).stem().string().c_str();
	Imported.Name = "ui_" + ToWidgetName(Stem.starts_with("ui_") ? Stem.c_str() + 3 : Stem.c_str()) + "_import";
	ImportNode(Imported, Xml.RootElement(), 0);

	if (Imported.Widgets.empty())
	{
		Error = xr_string(FileName) + " has no widgets";
		return false;
	}

	*this = Imported;
	return true;
}

void CUILayoutDocument::ListImportable(xr_vector<xr_string>& Out)
{
	FS_FileSet Files;
	FS.file_list(Files, _game_config_, FS_ListFiles, "*.xml");
	for (const FS_File& File : Files)
	{
		// Widescreen copies and texture descriptions are not windows
		if (File.name.starts_with("ui\\") && !File.name.ends_with("_16.xml") && !File.name.starts_with("ui\\textures_descr\\"))
		{
			Out.push_back(File.name.c_str());
		}
	}
}
