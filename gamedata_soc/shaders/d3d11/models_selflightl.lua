function normal(shader, t_base, t_second, t_detail)
    shader:begin("deffer_model", "deffer_base")
        :fog(false)
        :emissive(true)
    shader:dx10texture("s_base", t_base)
    shader:dx10sampler("smp_base")
    shader:dx10stencil(true, cmp_func.always, 255, 127, stencil_op.keep, stencil_op.replace, stencil_op.keep)
    shader:dx10stencil_ref(1)
end

function normal_ui(shader, t_base, t_second, t_detail)
    shader:begin("deffer_model", "ui_base")
        :fog(false)
        :emissive(true)
    shader:dx10texture("s_base", t_base)
    shader:dx10sampler("smp_base")
    shader:dx10stencil(true, cmp_func.always, 255, 127, stencil_op.keep, stencil_op.replace, stencil_op.keep)
    shader:dx10stencil_ref(1)
    shader:dx10texture("env_s0", "shaders\\newsky_viewport#small")
    shader:dx10texture("sky_s0", "shaders\\newsky_viewport")
    shader:dx10texture("s_material", "$user$material")
    shader:dx10sampler("smp_linear")
    shader:dx10sampler("smp_material")
end

function l_special(shader, t_base, t_second, t_detail)
    shader:begin("deffer_model", "accum_emissivel")
        :zb(true, false)
        :fog(false)
        :emissive(true)
    shader:dx10texture("s_base", t_base)
    shader:dx10sampler("smp_base")
end
